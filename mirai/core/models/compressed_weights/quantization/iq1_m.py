"""Canonical GGUF IQ1_M blocks with a bounded uniform-weight encoder."""

from __future__ import annotations

from functools import lru_cache

import torch

from .gguf_quant import QK_K, gguf_num_superblocks, validate_gguf_blocks


@lru_cache
def _grid(device):
    data = bytes.fromhex(_GRID_IDS)
    ids = torch.tensor(
        [data[i] | data[i + 1] << 8 for i in range(0, len(data), 2)],
        dtype=torch.int64, device=device,
    )
    powers = torch.tensor([3**i for i in range(8)], device=device)
    return ((ids[:, None] // powers) % 3 - 1).float()


def quantize_iq1_m(weight_2d: torch.Tensor) -> torch.Tensor:
    """Fit legal ternary codewords with uniform weights in each block."""
    if weight_2d.ndim != 2:
        raise ValueError("IQ1_M quantization requires a 2D weight.")
    flat = weight_2d.reshape(-1)
    blocks = flat.reshape(gguf_num_superblocks(flat.numel()), QK_K)
    device = blocks.device
    encoded = torch.empty((blocks.shape[0], 56), dtype=torch.uint8, device=device)
    grid = _grid(device)
    codes = torch.cat((grid + 0.125, grid - 0.125))
    norms = codes.square().sum(dim=-1)
    shifts = torch.arange(4, device=device) * 3
    nibbles = torch.arange(4, device=device) * 4
    with torch.autocast(device_type=device.type, enabled=False):
        for start in range(0, blocks.shape[0], 16):
            x = blocks[start:start + 16].float().reshape(-1, 16, 2, 8)
            if not torch.isfinite(x).all():
                raise ValueError("IQ1_M requires finite weights.")
            peak = x.abs().amax(dim=(-1, -2))
            d = (peak.amax(dim=-1) / 16.875).clamp(max=65504).half()
            master = d.float()[:, None]
            effective = torch.where(master > 0, master, 1.0)
            local = ((peak / (effective * 1.125) - 1) / 2).round().clamp(0, 7).long()
            targets = x / (effective * (2 * local + 1))[:, :, None, None]
            ids = (norms - 2 * (targets.reshape(-1, 8) @ codes.T)).argmin(dim=-1)
            ids = ids.reshape(-1, 32)
            output = encoded[start:start + x.shape[0]]
            output[:, :32] = ids & 255
            high = (ids >> 8).reshape(-1, 16, 2)
            output[:, 32:48] = high[:, :, 0] | (high[:, :, 1] << 4)
            scale_bits = d.view(torch.int16).long() & 65535
            words = (local.reshape(-1, 4, 4) << shifts).sum(dim=-1)
            words |= ((scale_bits[:, None] >> nibbles) & 15) << 12
            output[:, 48:] = torch.stack((words & 255, words >> 8), dim=-1).reshape(-1, 8)
    return encoded


def dequantize_iq1_m(blocks: torch.Tensor, *, shape, dtype, device) -> torch.Tensor:
    validate_gguf_blocks("gguf_iq1", blocks)
    b = blocks.to(device=device)
    scale_bytes = b[:, 48:].long().reshape(-1, 4, 2)
    words = scale_bytes[:, :, 0] | (scale_bytes[:, :, 1] << 8)
    nibbles = torch.arange(4, device=b.device) * 4
    scale_bits = ((words >> 12) << nibbles).sum(dim=-1)
    master = scale_bits.to(torch.int16).view(torch.float16).float()
    shifts = torch.arange(4, device=b.device) * 3
    local = ((words[:, :, None] >> shifts) & 7).reshape(-1, 16)
    high = b[:, 32:48].long()
    flags = torch.stack((high & 15, high >> 4), dim=-1).reshape(-1, 32)
    ids = b[:, :32].long() | ((flags & 7) << 8)
    delta = torch.where((flags & 8) == 0, 0.125, -0.125)
    grid = (_grid(b.device)[ids] + delta[:, :, None]).reshape(-1, 16, 2, 8)
    scales = master[:, None] * (2 * local + 1)
    return (grid * scales[:, :, None, None]).reshape(shape).to(dtype)


